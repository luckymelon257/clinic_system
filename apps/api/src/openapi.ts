import { ErrorEnvelope, routes, type RouteDef } from '@clinic/contracts';
import { z } from 'zod';

const schema = (s: z.ZodType, io: 'input' | 'output') => {
  const { $schema: _, ...json } = z.toJSONSchema(s, { io, unrepresentable: 'any' }) as Record<string, unknown>;
  return json;
};

function parameters(s: z.ZodType | undefined, where: 'path' | 'query') {
  if (!s) return [];
  const json = schema(s, 'input') as { properties?: Record<string, unknown>; required?: string[] };
  return Object.entries(json.properties ?? {}).map(([name, sch]) => ({
    name,
    in: where,
    required: where === 'path' || (json.required ?? []).includes(name),
    schema: sch,
  }));
}

/** OpenAPI 3.1 generated from the contract route table (zod 4 → JSON Schema 2020-12). */
export function openApiDocument() {
  const paths: Record<string, Record<string, unknown>> = {};
  const json = (s: z.ZodType, io: 'input' | 'output') => ({ 'application/json': { schema: schema(s, io) } });

  for (const [name, r] of Object.entries(routes) as [string, RouteDef][]) {
    const path = r.path.replace(/:(\w+)/g, '{$1}');
    const roles = r.roles === 'public' ? 'public' : r.roles === 'any' ? 'any authenticated user' : r.roles.join(', ');
    (paths[path] ??= {})[r.method.toLowerCase()] = {
      operationId: name,
      summary: r.summary,
      description: `Roles: ${roles}. Features: ${r.features.join(', ')}.`,
      tags: [r.path.split('/')[2]],
      ...(r.roles === 'public' ? {} : { security: [{ bearer: [] }] }),
      parameters: [...parameters(r.params, 'path'), ...parameters(r.query, 'query')],
      ...(r.body ? { requestBody: { required: true, content: json(r.body, 'input') } } : {}),
      responses: {
        [r.status ?? 200]: { description: 'OK', content: json(r.output, 'output') },
        default: { description: 'Error (400/401/403/404/409/422/500)', content: json(ErrorEnvelope, 'output') },
      },
    };
  }

  return {
    openapi: '3.1.0',
    info: { title: 'Clinic API', version: '0.1.0', description: 'Hospital Management System, generated by the @clinic/contracts route table' },
    components: { securitySchemes: { bearer: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' } } },
    paths,
  };
}
