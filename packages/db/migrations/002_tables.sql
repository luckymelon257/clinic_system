-- 002: таблиці, ключі, CHECK / UNIQUE / EXCLUDE обмеження
-- Audit-поля (created_at/created_by/updated_at/updated_by) заповнює тригер tf_set_audit_fields (004).
-- created_at без DEFAULT: тригер ставить now(), якщо значення не передано (seed може передати історичну дату).

CREATE TABLE roles (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        user_role NOT NULL CONSTRAINT ux_roles_code UNIQUE,
  name        text NOT NULL,
  description text
);

CREATE TABLE users (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text NOT NULL CONSTRAINT ck_users_email CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  password_hash text NOT NULL,
  role_id       int NOT NULL REFERENCES roles (id),
  full_name     text NOT NULL CONSTRAINT ck_users_full_name CHECK (btrim(full_name) <> ''),
  is_active     boolean NOT NULL DEFAULT true,
  last_login_at timestamptz,
  created_at    timestamptz NOT NULL,
  created_by    int REFERENCES users (id),
  updated_at    timestamptz,
  updated_by    int REFERENCES users (id),
  deleted_at    timestamptz,
  deleted_by    int REFERENCES users (id)
);

CREATE TABLE specializations (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL CONSTRAINT ux_specializations_name UNIQUE,
  description text
);

CREATE TABLE departments (
  id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL CONSTRAINT ux_departments_name UNIQUE,
  description    text,
  phone          d_phone,
  head_doctor_id int, -- FK додається нижче (циклічна залежність з doctors)
  created_at     timestamptz NOT NULL,
  created_by     int REFERENCES users (id),
  updated_at     timestamptz,
  updated_by     int REFERENCES users (id),
  deleted_at     timestamptz,
  deleted_by     int REFERENCES users (id)
);

CREATE TABLE doctors (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           int NOT NULL CONSTRAINT ux_doctors_user UNIQUE REFERENCES users (id),
  department_id     int NOT NULL REFERENCES departments (id),
  specialization_id int NOT NULL REFERENCES specializations (id),
  license_number    text NOT NULL CONSTRAINT ux_doctors_license UNIQUE,
  consultation_fee  d_money NOT NULL DEFAULT 0,
  phone             d_phone,
  hired_on          date,
  created_at        timestamptz NOT NULL,
  created_by        int REFERENCES users (id),
  updated_at        timestamptz,
  updated_by        int REFERENCES users (id),
  deleted_at        timestamptz,
  deleted_by        int REFERENCES users (id)
);

ALTER TABLE departments
  ADD CONSTRAINT fk_departments_head_doctor FOREIGN KEY (head_doctor_id) REFERENCES doctors (id);

CREATE TABLE doctor_schedules (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id    int NOT NULL REFERENCES doctors (id),
  weekday      smallint NOT NULL CONSTRAINT ck_doctor_schedules_weekday CHECK (weekday BETWEEN 1 AND 7),
  start_time   time NOT NULL,
  end_time     time NOT NULL,
  slot_minutes int NOT NULL DEFAULT 30 CONSTRAINT ck_doctor_schedules_slot CHECK (slot_minutes BETWEEN 5 AND 240),
  room         text,
  created_at   timestamptz NOT NULL,
  created_by   int REFERENCES users (id),
  updated_at   timestamptz,
  updated_by   int REFERENCES users (id),
  CONSTRAINT ck_doctor_schedules_time CHECK (end_time > start_time),
  CONSTRAINT ux_doctor_schedules_day UNIQUE (doctor_id, weekday)
);

CREATE TABLE patients (
  id                      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id                 int CONSTRAINT ux_patients_user UNIQUE REFERENCES users (id),
  last_name               text NOT NULL CONSTRAINT ck_patients_last_name CHECK (btrim(last_name) <> ''),
  first_name              text NOT NULL CONSTRAINT ck_patients_first_name CHECK (btrim(first_name) <> ''),
  middle_name             text,
  birth_date              date NOT NULL CONSTRAINT ck_patients_birth_date CHECK (birth_date >= DATE '1900-01-01'),
  sex                     sex_type NOT NULL,
  phone                   d_phone,
  email                   text CONSTRAINT ck_patients_email CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  address                 text,
  blood_type              blood_type,
  emergency_contact_name  text,
  emergency_contact_phone d_phone,
  created_at              timestamptz NOT NULL,
  created_by              int REFERENCES users (id),
  updated_at              timestamptz,
  updated_by              int REFERENCES users (id),
  deleted_at              timestamptz,
  deleted_by              int REFERENCES users (id)
);

CREATE TABLE insurance_companies (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL CONSTRAINT ux_insurance_companies_name UNIQUE,
  phone      d_phone,
  email      text,
  created_at timestamptz NOT NULL,
  created_by int REFERENCES users (id),
  updated_at timestamptz,
  updated_by int REFERENCES users (id),
  deleted_at timestamptz,
  deleted_by int REFERENCES users (id)
);

CREATE TABLE patient_insurances (
  id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id       int NOT NULL REFERENCES patients (id),
  company_id       int NOT NULL REFERENCES insurance_companies (id),
  policy_number    text NOT NULL,
  coverage_percent numeric(5, 2) NOT NULL,
  valid_from       date NOT NULL,
  valid_to         date,
  created_at       timestamptz NOT NULL,
  created_by       int REFERENCES users (id),
  updated_at       timestamptz,
  updated_by       int REFERENCES users (id),
  CONSTRAINT ck_patient_insurances_coverage CHECK (coverage_percent BETWEEN 0 AND 100), -- BR-10
  CONSTRAINT ck_patient_insurances_period CHECK (valid_to IS NULL OR valid_to >= valid_from),
  CONSTRAINT ux_patient_insurances_policy UNIQUE (company_id, policy_number)
);

CREATE TABLE appointments (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id    int NOT NULL REFERENCES patients (id),
  doctor_id     int NOT NULL REFERENCES doctors (id),
  starts_at     timestamptz NOT NULL,
  ends_at       timestamptz NOT NULL,
  status        appointment_status NOT NULL DEFAULT 'scheduled',
  reason        text,
  cancel_reason text,
  created_at    timestamptz NOT NULL,
  created_by    int REFERENCES users (id),
  updated_at    timestamptz,
  updated_by    int REFERENCES users (id),
  CONSTRAINT ck_appointments_time CHECK (ends_at > starts_at), -- BR-9
  -- BR-1: у лікаря немає записів, що перетинаються (скасовані / неявки не враховуються)
  CONSTRAINT ex_appointments_doctor_overlap EXCLUDE USING gist (
    doctor_id WITH =,
    tstzrange(starts_at, ends_at) WITH &&
  ) WHERE (status NOT IN ('cancelled', 'no_show'))
);

CREATE TABLE wards (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id int NOT NULL REFERENCES departments (id),
  ward_number   text NOT NULL CONSTRAINT ux_wards_number UNIQUE,
  ward_type     ward_type NOT NULL,
  capacity      int NOT NULL CONSTRAINT ck_wards_capacity CHECK (capacity > 0),
  daily_rate    d_money NOT NULL,
  floor         int,
  created_at    timestamptz NOT NULL,
  created_by    int REFERENCES users (id),
  updated_at    timestamptz,
  updated_by    int REFERENCES users (id),
  deleted_at    timestamptz,
  deleted_by    int REFERENCES users (id)
);

CREATE TABLE beds (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ward_id    int NOT NULL REFERENCES wards (id),
  bed_number text NOT NULL,
  status     bed_status NOT NULL DEFAULT 'available',
  created_at timestamptz NOT NULL,
  created_by int REFERENCES users (id),
  updated_at timestamptz,
  updated_by int REFERENCES users (id),
  deleted_at timestamptz,
  deleted_by int REFERENCES users (id),
  CONSTRAINT ux_beds_ward_number UNIQUE (ward_id, bed_number)
);

CREATE TABLE admissions (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id        int NOT NULL REFERENCES patients (id),
  bed_id            int NOT NULL REFERENCES beds (id),
  doctor_id         int NOT NULL REFERENCES doctors (id),
  admitted_at       timestamptz NOT NULL DEFAULT now(),
  discharged_at     timestamptz,
  reason            text,
  discharge_summary text,
  status            admission_status NOT NULL DEFAULT 'active',
  created_at        timestamptz NOT NULL,
  created_by        int REFERENCES users (id),
  updated_at        timestamptz,
  updated_by        int REFERENCES users (id),
  CONSTRAINT ck_admissions_dates CHECK (discharged_at IS NULL OR discharged_at >= admitted_at), -- BR-9
  CONSTRAINT ck_admissions_status CHECK ((status = 'active') = (discharged_at IS NULL)),
  -- BR-2: одне ліжко — одна активна госпіталізація
  CONSTRAINT ex_admissions_bed_active EXCLUDE USING gist (
    bed_id WITH =,
    tstzrange(admitted_at, discharged_at) WITH &&
  ) WHERE (status = 'active')
);

CREATE TABLE medical_records (
  id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id  int CONSTRAINT ux_medical_records_appointment UNIQUE REFERENCES appointments (id),
  admission_id    int REFERENCES admissions (id),
  patient_id      int NOT NULL REFERENCES patients (id),
  doctor_id       int NOT NULL REFERENCES doctors (id),
  complaints      text,
  examination     text,
  conclusion      text,
  recommendations text,
  created_at      timestamptz NOT NULL,
  created_by      int REFERENCES users (id),
  updated_at      timestamptz,
  updated_by      int REFERENCES users (id),
  CONSTRAINT ck_medical_records_source CHECK (num_nonnulls(appointment_id, admission_id) = 1)
);

CREATE TABLE icd10_codes (
  code  text PRIMARY KEY CONSTRAINT ck_icd10_codes_format CHECK (code ~ '^[A-Z][0-9]{2}(\.[0-9A-Z]{1,4})?$'),
  title text NOT NULL
);

CREATE TABLE diagnoses (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medical_record_id int NOT NULL REFERENCES medical_records (id),
  icd10_code        text NOT NULL REFERENCES icd10_codes (code),
  kind              diagnosis_kind NOT NULL,
  notes             text,
  created_at        timestamptz NOT NULL,
  created_by        int REFERENCES users (id),
  updated_at        timestamptz,
  updated_by        int REFERENCES users (id),
  CONSTRAINT ux_diagnoses_record_code UNIQUE (medical_record_id, icd10_code)
);

CREATE TABLE medications (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  form       medication_form NOT NULL,
  strength   text,
  unit_price d_money NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL,
  created_by int REFERENCES users (id),
  updated_at timestamptz,
  updated_by int REFERENCES users (id),
  deleted_at timestamptz,
  deleted_by int REFERENCES users (id),
  CONSTRAINT ux_medications_name_form UNIQUE (name, form, strength)
);

CREATE TABLE prescriptions (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medical_record_id int NOT NULL REFERENCES medical_records (id),
  issued_at         timestamptz NOT NULL DEFAULT now(),
  valid_until       date,
  created_at        timestamptz NOT NULL,
  created_by        int REFERENCES users (id),
  updated_at        timestamptz,
  updated_by        int REFERENCES users (id)
);

CREATE TABLE prescription_items (
  id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prescription_id int NOT NULL REFERENCES prescriptions (id),
  medication_id   int NOT NULL REFERENCES medications (id),
  dosage          text NOT NULL,
  frequency       text NOT NULL,
  duration_days   int NOT NULL CONSTRAINT ck_prescription_items_duration CHECK (duration_days BETWEEN 1 AND 365),
  quantity        int NOT NULL CONSTRAINT ck_prescription_items_quantity CHECK (quantity > 0),
  instructions    text
);

CREATE TABLE lab_test_types (
  id      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code    text NOT NULL CONSTRAINT ux_lab_test_types_code UNIQUE,
  name    text NOT NULL,
  unit    text,
  ref_min numeric,
  ref_max numeric,
  price   d_money NOT NULL DEFAULT 0,
  CONSTRAINT ck_lab_test_types_range CHECK (ref_min IS NULL OR ref_max IS NULL OR ref_min <= ref_max)
);

CREATE TABLE lab_orders (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id        int NOT NULL REFERENCES patients (id),
  doctor_id         int NOT NULL REFERENCES doctors (id),
  medical_record_id int REFERENCES medical_records (id),
  priority          lab_priority NOT NULL DEFAULT 'routine',
  status            lab_order_status NOT NULL DEFAULT 'ordered',
  ordered_at        timestamptz NOT NULL DEFAULT now(),
  completed_at      timestamptz,
  created_at        timestamptz NOT NULL,
  created_by        int REFERENCES users (id),
  updated_at        timestamptz,
  updated_by        int REFERENCES users (id),
  CONSTRAINT ck_lab_orders_completed CHECK (completed_at IS NULL OR completed_at >= ordered_at)
);

CREATE TABLE lab_order_items (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_order_id int NOT NULL REFERENCES lab_orders (id),
  test_type_id int NOT NULL REFERENCES lab_test_types (id),
  CONSTRAINT ux_lab_order_items_test UNIQUE (lab_order_id, test_type_id)
);

CREATE TABLE lab_results (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_order_id  int NOT NULL,
  test_type_id  int NOT NULL,
  value_numeric numeric,
  value_text    text,
  is_abnormal   boolean,
  recorded_at   timestamptz NOT NULL DEFAULT now(),
  created_at    timestamptz NOT NULL,
  created_by    int REFERENCES users (id),
  updated_at    timestamptz,
  updated_by    int REFERENCES users (id),
  CONSTRAINT ck_lab_results_value CHECK (value_numeric IS NOT NULL OR value_text IS NOT NULL),
  CONSTRAINT ux_lab_results_test UNIQUE (lab_order_id, test_type_id),
  -- результат можна внести лише для тесту, що є у направленні
  CONSTRAINT fk_lab_results_order_item FOREIGN KEY (lab_order_id, test_type_id)
    REFERENCES lab_order_items (lab_order_id, test_type_id)
);

CREATE TABLE invoices (
  id                         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number                     text NOT NULL CONSTRAINT ux_invoices_number UNIQUE,
  patient_id                 int NOT NULL REFERENCES patients (id),
  appointment_id             int REFERENCES appointments (id),
  admission_id               int REFERENCES admissions (id),
  status                     invoice_status NOT NULL DEFAULT 'draft',
  subtotal                   d_money NOT NULL DEFAULT 0,
  insurance_coverage_percent numeric(5, 2) NOT NULL DEFAULT 0,
  insurance_amount           d_money NOT NULL DEFAULT 0,
  total_due                  d_money NOT NULL DEFAULT 0,
  paid_amount                d_money NOT NULL DEFAULT 0,
  issued_at                  timestamptz,
  due_date                   date,
  created_at                 timestamptz NOT NULL,
  created_by                 int REFERENCES users (id),
  updated_at                 timestamptz,
  updated_by                 int REFERENCES users (id),
  CONSTRAINT ck_invoices_coverage CHECK (insurance_coverage_percent BETWEEN 0 AND 100), -- BR-10
  CONSTRAINT ck_invoices_paid CHECK (paid_amount <= total_due), -- BR-7 (страховка на рівні таблиці)
  CONSTRAINT ck_invoices_totals CHECK (total_due = subtotal - insurance_amount)
);

CREATE TABLE invoice_items (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id  int NOT NULL REFERENCES invoices (id),
  item_type   invoice_item_type NOT NULL,
  description text NOT NULL,
  quantity    numeric(10, 2) NOT NULL CONSTRAINT ck_invoice_items_quantity CHECK (quantity > 0),
  unit_price  d_money NOT NULL,
  amount      numeric(12, 2) GENERATED ALWAYS AS (round(quantity * unit_price, 2)) STORED,
  created_at  timestamptz NOT NULL,
  created_by  int REFERENCES users (id),
  updated_at  timestamptz,
  updated_by  int REFERENCES users (id)
);

CREATE TABLE payments (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id int NOT NULL REFERENCES invoices (id),
  amount     d_money NOT NULL CONSTRAINT ck_payments_amount CHECK (amount > 0),
  method     payment_method NOT NULL,
  reference  text,
  paid_at    timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL,
  created_by int REFERENCES users (id),
  updated_at timestamptz,
  updated_by int REFERENCES users (id)
);

CREATE TABLE audit_log (
  id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name     text NOT NULL,
  record_id      int NOT NULL,
  operation      audit_operation NOT NULL,
  changed_fields text[],
  old_data       jsonb,
  new_data       jsonb,
  changed_at     timestamptz NOT NULL DEFAULT now(),
  changed_by     int REFERENCES users (id)
);

