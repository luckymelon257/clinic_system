CREATE TYPE staff_role           AS ENUM ('doctor', 'nurse');               -- contracts: StaffRole
CREATE TYPE interaction_severity AS ENUM ('minor', 'moderate', 'major');    -- contracts: InteractionSeverity

-- Час графа: epoch ms (bigint); відкрите перебування ('infinity') → 9e15 (D-23, docs/06 §4)
CREATE FUNCTION fn_epoch_ms(p_ts timestamptz) RETURNS bigint
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT CASE WHEN p_ts IS NULL OR p_ts = 'infinity'::timestamptz THEN 9000000000000000
              ELSE (extract(epoch FROM p_ts) * 1000)::bigint END
$$;

-- ---------- кімнати (D-21) ----------
CREATE TABLE rooms (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ward_id     int NOT NULL REFERENCES wards (id),
  room_number text NOT NULL CONSTRAINT ck_rooms_number CHECK (btrim(room_number) <> ''),
  created_at  timestamptz NOT NULL,
  created_by  int REFERENCES users (id),
  updated_at  timestamptz,
  updated_by  int REFERENCES users (id),
  CONSTRAINT ux_rooms_ward_number UNIQUE (ward_id, room_number),
  CONSTRAINT ux_rooms_id_ward UNIQUE (id, ward_id) -- ціль складеного FK з beds: кімната ліжка — у тій самій палаті
);

ALTER TABLE beds ADD COLUMN room_id int;
ALTER TABLE beds ADD CONSTRAINT fk_beds_room_ward FOREIGN KEY (room_id, ward_id) REFERENCES rooms (id, ward_id);

-- Ліжко без кімнати → перша кімната палати (створюється, якщо її немає). Так довідникові ліжка Лаб 1
-- (seed 01) автоматично отримують по одній кімнаті на палату.
CREATE FUNCTION tf_beds_default_room() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.room_id IS NULL THEN
    SELECT r.id INTO NEW.room_id FROM rooms r WHERE r.ward_id = NEW.ward_id ORDER BY r.id LIMIT 1;
    IF NEW.room_id IS NULL THEN
      INSERT INTO rooms (ward_id, room_number)
      SELECT w.id, w.ward_number FROM wards w WHERE w.id = NEW.ward_id
      RETURNING id INTO NEW.room_id;
    END IF;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_beds_default_room
BEFORE INSERT OR UPDATE OF ward_id, room_id ON beds
FOR EACH ROW EXECUTE FUNCTION tf_beds_default_room();

-- Оновлення існуючої бази (на свіжій базі ліжок ще немає — no-op)
INSERT INTO rooms (ward_id, room_number, created_at)
SELECT w.id, w.ward_number, w.created_at FROM wards w
WHERE EXISTS (SELECT 1 FROM beds b WHERE b.ward_id = w.id AND b.room_id IS NULL);
UPDATE beds b SET room_id = r.id FROM rooms r WHERE r.ward_id = b.ward_id AND b.room_id IS NULL;

