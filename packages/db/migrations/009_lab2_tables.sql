-- Вузли :Person (:Patient / :Staff)
CREATE VIEW v_graph_persons AS
SELECT 'patient'::text AS person_kind, p.id AS person_id,
       fn_full_name(p.last_name, p.first_name, p.middle_name) AS name, NULL::text AS role
FROM patients p
UNION ALL
SELECT 'staff', s.id, s.full_name, s.role::text
FROM staff s;

-- Вузли :Place (:Room / :Ward / :Office); office = кабінет лікаря, id = doctors.id
CREATE VIEW v_graph_places AS
SELECT 'room'::text AS place_kind, r.id AS place_id, r.room_number AS name, r.ward_id,
       w.department_id, w.ward_type::text AS ward_type
FROM rooms r JOIN wards w ON w.id = r.ward_id
UNION ALL
SELECT 'ward', w.id, w.ward_number, NULL::int, w.department_id, w.ward_type::text
FROM wards w
UNION ALL
SELECT 'office', d.id, coalesce(u.full_name, 'Кабінет #' || d.id), NULL::int, d.department_id, NULL::text
FROM doctors d LEFT JOIN users u ON u.id = d.user_id;

-- Ребра PRESENT: хто, де, коли. period = напіввідкритий [f, t); відкрите перебування — t = 'infinity'.
-- Вирази period збігаються з GiST-індексами вище, тож фільтр period && … проштовхується в кожну гілку UNION ALL.
-- Джерела: admissions ⋈ beds ⋈ rooms / wards, staff_shifts, appointments ⋈ doctors ⋈ staff (8+ таблиць).
CREATE VIEW v_presence AS
SELECT 'patient'::text AS person_kind, a.patient_id AS person_id, 'room'::text AS place_kind, b.room_id AS place_id,
       a.admitted_at AS f, coalesce(a.discharged_at, 'infinity'::timestamptz) AS t,
       tstzrange(a.admitted_at, a.discharged_at) AS period,
       'admission'::text AS src, a.id AS src_id
FROM admissions a JOIN beds b ON b.id = a.bed_id
WHERE b.room_id IS NOT NULL
UNION ALL
SELECT 'patient', a.patient_id, 'ward', b.ward_id,
       a.admitted_at, coalesce(a.discharged_at, 'infinity'::timestamptz),
       tstzrange(a.admitted_at, a.discharged_at), 'admission', a.id
FROM admissions a JOIN beds b ON b.id = a.bed_id
UNION ALL
SELECT 'staff', s.staff_id, 'ward', s.ward_id, s.starts_at, s.ends_at, tstzrange(s.starts_at, s.ends_at), 'shift', s.id
FROM staff_shifts s
UNION ALL
SELECT 'patient', ap.patient_id, 'office', ap.doctor_id, ap.starts_at, ap.ends_at, tstzrange(ap.starts_at, ap.ends_at),
       'appointment', ap.id
FROM appointments ap
WHERE ap.status NOT IN ('cancelled', 'no_show')
UNION ALL
SELECT 'staff', st.id, 'office', ap.doctor_id, ap.starts_at, ap.ends_at, tstzrange(ap.starts_at, ap.ends_at),
       'appointment', ap.id
FROM appointments ap
JOIN staff st ON st.doctor_id = ap.doctor_id
WHERE ap.status NOT IN ('cancelled', 'no_show');

COMMENT ON VIEW v_presence IS
  'Факти присутності особи в місці (ребра PRESENT графа). Контакт = дві особи в одному місці з перетином інтервалів у межах вікна.';

-- Ребра TAKES: пацієнт приймає препарат з issued_at протягом duration_days
CREATE VIEW v_takes AS
SELECT pi.id AS rx_item_id, mr.patient_id, pi.medication_id,
       rx.issued_at AS f, rx.issued_at + make_interval(days => pi.duration_days) AS t
FROM prescription_items pi
JOIN prescriptions rx ON rx.id = pi.prescription_id
JOIN medical_records mr ON mr.id = rx.medical_record_id;

-- Взаємодії в обох напрямках (для пошуку за будь-яким кінцем пари)
CREATE VIEW v_medication_interactions AS
SELECT mi.id, mi.medication_a, ma.name AS medication_a_name, mi.medication_b, mb.name AS medication_b_name,
       mi.severity, mi.description
FROM medication_interactions mi
JOIN medications ma ON ma.id = mi.medication_a
JOIN medications mb ON mb.id = mi.medication_b;

CREATE VIEW v_drug_class_interactions AS
SELECT ci.id, ci.class_a, ca.name AS class_a_name, ci.class_b, cb.name AS class_b_name, ci.severity, ci.description
FROM drug_class_interactions ci
JOIN drug_classes ca ON ca.id = ci.class_a
JOIN drug_classes cb ON cb.id = ci.class_b;

CREATE VIEW v_drug_classes AS
SELECT c.id, c.code, c.name,
       coalesce((SELECT array_agg(mc.medication_id ORDER BY mc.medication_id)
                 FROM medication_classes mc WHERE mc.class_id = c.id), '{}') AS medication_ids
FROM drug_classes c;

CREATE VIEW v_medication_classes AS
SELECT mc.medication_id, m.name AS medication_name, mc.class_id, c.code AS class_code, c.name AS class_name
FROM medication_classes mc
JOIN medications m ON m.id = mc.medication_id
JOIN drug_classes c ON c.id = mc.class_id;

-- Очікувані кількості вузлів / ребер графа після повного ETL (гейт: = MATCH-підрахунки в Neo4j)
CREATE VIEW v_graph_counts AS
SELECT 'node'::text AS kind, 'Patient'::text AS label, count(*)::bigint AS count FROM patients
UNION ALL SELECT 'node', 'Staff', count(*) FROM staff
UNION ALL SELECT 'node', 'Room', count(*) FROM rooms
UNION ALL SELECT 'node', 'Ward', count(*) FROM wards
UNION ALL SELECT 'node', 'Office', count(*) FROM doctors
UNION ALL SELECT 'node', 'Medication', count(*) FROM medications
UNION ALL SELECT 'node', 'DrugClass', count(*) FROM drug_classes
UNION ALL SELECT 'rel', 'PRESENT', count(*) FROM v_presence
UNION ALL SELECT 'rel', 'IN', count(*) FROM rooms
UNION ALL SELECT 'rel', 'IN_CLASS', count(*) FROM medication_classes
UNION ALL SELECT 'rel', 'INTERACTS', (SELECT count(*) FROM medication_interactions) + (SELECT count(*) FROM drug_class_interactions)
UNION ALL SELECT 'rel', 'TAKES', count(*) FROM v_takes;

-- Читання для API (F-38, F-39)
CREATE VIEW v_staff AS
SELECT s.id, s.full_name, s.role, s.doctor_id, s.department_id, dep.name AS department_name, s.is_float
FROM staff s JOIN departments dep ON dep.id = s.department_id
WHERE s.deleted_at IS NULL;

CREATE VIEW v_staff_shifts AS
SELECT sh.id, sh.staff_id, s.full_name AS staff_name, s.role AS staff_role, sh.ward_id, w.ward_number,
       sh.starts_at, sh.ends_at
FROM staff_shifts sh
JOIN staff s ON s.id = sh.staff_id
JOIN wards w ON w.id = sh.ward_id;

CREATE VIEW v_rooms AS
SELECT r.id, r.room_number, r.ward_id, w.ward_number, w.ward_type, w.department_id,
       (SELECT count(*)::int FROM beds b WHERE b.room_id = r.id AND b.deleted_at IS NULL) AS beds
FROM rooms r JOIN wards w ON w.id = r.ward_id
WHERE w.deleted_at IS NULL;

-- =====================================================================================================
-- Transactional outbox (D-23, BR-11). Тригер пише подію в ТІЙ САМІЙ транзакції, що й зміна; воркер
-- (packages/graph sync) забирає пачку fn_graph_outbox_claim → застосовує в Neo4j (MERGE за id) → CALL sp_graph_outbox_ack.
-- Подія = знімок поточного стану одного рядка-джерела (payload). Для ребер присутності payload містить УСІ
-- ребра цього джерела (src, src_id); воркер замінює їх цілком → застосування ідемпотентне.
-- Масове завантаження: SET session_replication_role = replica вимикає тригери (бенч-дані → повний ETL).
-- =====================================================================================================
CREATE TABLE graph_outbox (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  entity       text NOT NULL CONSTRAINT ck_graph_outbox_entity CHECK (entity IN (
                 'patient', 'staff', 'ward', 'room', 'office', 'presence', 'takes',
                 'medication', 'drug_class', 'medication_class', 'medication_interaction', 'class_interaction')),
  entity_key   text NOT NULL,            -- id вузла / 'admission:17' / '3:9' (пара)
  op           text NOT NULL CONSTRAINT ck_graph_outbox_op CHECK (op IN ('upsert', 'delete')),
  payload      jsonb NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
  claimed_at   timestamptz,
  claimed_by   text,
  attempts     int NOT NULL DEFAULT 0,
  processed_at timestamptz,
  last_error   text
);
CREATE INDEX ix_graph_outbox_pending ON graph_outbox (id) WHERE processed_at IS NULL;
CREATE INDEX ix_graph_outbox_processed ON graph_outbox USING brin (processed_at);
COMMENT ON TABLE graph_outbox IS 'Transactional outbox PG → Neo4j: події змін у тій самій транзакції, що й зміна';

-- Payload ребер присутності одного джерела (масив; порожній = джерело більше не дає присутності)
CREATE FUNCTION fn_graph_presence_payload(p_src text, p_src_id int) RETURNS jsonb
LANGUAGE sql STABLE AS $$
  SELECT jsonb_build_object('src', p_src, 'srcId', p_src_id, 'edges', coalesce(jsonb_agg(jsonb_build_object(
           'personKind', v.person_kind, 'personId', v.person_id, 'placeKind', v.place_kind, 'placeId', v.place_id,
           'f', fn_epoch_ms(v.f), 't', fn_epoch_ms(v.t)) ORDER BY v.person_kind, v.place_kind), '[]'::jsonb))
  FROM v_presence v
  WHERE v.src = p_src AND v.src_id = p_src_id
$$;

CREATE FUNCTION tf_graph_outbox() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  r      record := CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  v_op   text := CASE WHEN TG_OP = 'DELETE' THEN 'delete' ELSE 'upsert' END;
  v_ent  text;
  v_key  text;
  v_body jsonb;
BEGIN
  CASE TG_TABLE_NAME
    WHEN 'patients' THEN
      v_ent := 'patient'; v_key := r.id::text;
      v_body := jsonb_build_object('id', r.id, 'name', fn_full_name(r.last_name, r.first_name, r.middle_name));
    WHEN 'staff' THEN
      v_ent := 'staff'; v_key := r.id::text;
      v_body := jsonb_build_object('id', r.id, 'name', r.full_name, 'role', r.role);
    WHEN 'wards' THEN
      v_ent := 'ward'; v_key := r.id::text;
      v_body := jsonb_build_object('id', r.id, 'name', r.ward_number, 'departmentId', r.department_id, 'type', r.ward_type);
    WHEN 'rooms' THEN
      v_ent := 'room'; v_key := r.id::text;
      v_body := jsonb_build_object('id', r.id, 'name', r.room_number, 'wardId', r.ward_id);
    WHEN 'doctors' THEN
      v_ent := 'office'; v_key := r.id::text;
      v_body := jsonb_build_object('id', r.id, 'departmentId', r.department_id);
    WHEN 'admissions' THEN
      v_ent := 'presence'; v_key := 'admission:' || r.id; v_op := 'upsert';
      v_body := fn_graph_presence_payload('admission', r.id);
    WHEN 'staff_shifts' THEN
      v_ent := 'presence'; v_key := 'shift:' || r.id; v_op := 'upsert';
      v_body := fn_graph_presence_payload('shift', r.id);
    WHEN 'appointments' THEN
      v_ent := 'presence'; v_key := 'appointment:' || r.id; v_op := 'upsert';
      v_body := fn_graph_presence_payload('appointment', r.id);
    WHEN 'prescription_items' THEN
      v_ent := 'takes'; v_key := r.id::text;
      SELECT jsonb_build_object('rxItemId', t.rx_item_id, 'patientId', t.patient_id, 'medicationId', t.medication_id,
                                'f', fn_epoch_ms(t.f), 't', fn_epoch_ms(t.t))
        INTO v_body FROM v_takes t WHERE t.rx_item_id = r.id;
      v_body := coalesce(v_body, jsonb_build_object('rxItemId', r.id));
    WHEN 'medications' THEN
      v_ent := 'medication'; v_key := r.id::text;
      v_body := jsonb_build_object('id', r.id, 'name', r.name);
    WHEN 'drug_classes' THEN
      v_ent := 'drug_class'; v_key := r.id::text;
      v_body := jsonb_build_object('id', r.id, 'code', r.code, 'name', r.name);
    WHEN 'medication_classes' THEN
      -- повний набір класів препарату (заміна цілком)
      v_ent := 'medication_class'; v_key := r.medication_id::text; v_op := 'upsert';
      v_body := jsonb_build_object('medicationId', r.medication_id, 'classIds',
        coalesce((SELECT jsonb_agg(mc.class_id ORDER BY mc.class_id) FROM medication_classes mc
                  WHERE mc.medication_id = r.medication_id), '[]'::jsonb));
    WHEN 'medication_interactions' THEN
      v_ent := 'medication_interaction'; v_key := r.medication_a || ':' || r.medication_b;
      v_body := jsonb_build_object('a', r.medication_a, 'b', r.medication_b, 'severity', r.severity);
    WHEN 'drug_class_interactions' THEN
      v_ent := 'class_interaction'; v_key := r.class_a || ':' || r.class_b;
      v_body := jsonb_build_object('a', r.class_a, 'b', r.class_b, 'severity', r.severity);
    ELSE
      RAISE EXCEPTION 'tf_graph_outbox: таблиця % не підтримується', TG_TABLE_NAME;
  END CASE;
  INSERT INTO graph_outbox (entity, entity_key, op, payload) VALUES (v_ent, v_key, v_op, v_body);
  RETURN NULL;
END $$;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['patients', 'staff', 'wards', 'rooms', 'doctors', 'admissions', 'staff_shifts',
                           'appointments', 'prescription_items', 'medications', 'drug_classes', 'medication_classes',
                           'medication_interactions', 'drug_class_interactions'] LOOP
    EXECUTE format('CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION tf_graph_outbox()',
                   'trg_' || t || '_graph_outbox', t);
  END LOOP;
END $$;

-- Забрати пачку подій (кілька воркерів не заважають один одному — SKIP LOCKED; незавершена пачка
-- повертається в чергу після p_lease). Подію застосовують у порядку id.
CREATE FUNCTION fn_graph_outbox_claim(p_worker text, p_limit int DEFAULT 500, p_lease interval DEFAULT '30 seconds')
RETURNS SETOF graph_outbox
LANGUAGE sql VOLATILE AS $$
  UPDATE graph_outbox o
  SET claimed_at = clock_timestamp(), claimed_by = p_worker, attempts = o.attempts + 1
  WHERE o.id IN (
    SELECT q.id FROM graph_outbox q
    WHERE q.processed_at IS NULL
      AND (q.claimed_at IS NULL OR q.claimed_at < clock_timestamp() - p_lease)
    ORDER BY q.id
    LIMIT p_limit
    FOR UPDATE SKIP LOCKED
  )
  RETURNING o.*
$$;

-- Підтвердити пачку: успіх → processed_at; помилка → повернути в чергу з last_error
CREATE PROCEDURE sp_graph_outbox_ack(p_ids bigint[], p_error text DEFAULT NULL)
LANGUAGE plpgsql AS $$
BEGIN
  IF p_error IS NULL THEN
    UPDATE graph_outbox SET processed_at = clock_timestamp(), last_error = NULL
    WHERE id = ANY (p_ids) AND processed_at IS NULL;
  ELSE
    UPDATE graph_outbox SET claimed_at = NULL, claimed_by = NULL, last_error = left(p_error, 2000)
    WHERE id = ANY (p_ids) AND processed_at IS NULL;
  END IF;
END $$;

-- Прибирання оброблених подій старших за p_older
CREATE PROCEDURE sp_graph_outbox_purge(p_older interval DEFAULT '1 day')
LANGUAGE sql AS $$
  DELETE FROM graph_outbox WHERE processed_at < clock_timestamp() - p_older
$$;

-- Стан синхронізації для asOf / lagMs (BR-11) і /api/health (F-45)
CREATE VIEW v_graph_sync_status AS
SELECT (SELECT count(*) FROM graph_outbox WHERE processed_at IS NULL)::int AS pending,
       (SELECT min(created_at) FROM graph_outbox WHERE processed_at IS NULL) AS oldest_pending_at,
       (SELECT max(processed_at) FROM graph_outbox) AS last_processed_at,
       coalesce((extract(epoch FROM clock_timestamp() - (SELECT min(created_at) FROM graph_outbox
                                                         WHERE processed_at IS NULL)) * 1000)::bigint, 0) AS lag_ms;

-- ---------- процедури персоналу (F-38) ----------
CREATE PROCEDURE sp_staff_shift_add(p_staff_id int, p_ward_id int, p_starts_at timestamptz, p_ends_at timestamptz,
                                    INOUT p_id int DEFAULT NULL)
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM staff WHERE id = p_staff_id AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'Співробітника #% не знайдено', p_staff_id USING ERRCODE = 'P0002';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM wards WHERE id = p_ward_id AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'Палату #% не знайдено', p_ward_id USING ERRCODE = 'P0002';
  END IF;
  IF p_ends_at <= p_starts_at THEN
    RAISE EXCEPTION 'Кінець зміни має бути пізніше за початок' USING ERRCODE = 'P0070';
  END IF;
  -- перетин змін одного співробітника → 23P01 (ex_staff_shifts_overlap) → HTTP 409
  INSERT INTO staff_shifts (staff_id, ward_id, starts_at, ends_at)
  VALUES (p_staff_id, p_ward_id, p_starts_at, p_ends_at)
  RETURNING id INTO p_id;
END $$;

