  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id   int NOT NULL REFERENCES staff (id),
  ward_id    int NOT NULL REFERENCES wards (id),
  starts_at  timestamptz NOT NULL,
  ends_at    timestamptz NOT NULL,
