-- class_a <= class_b; class_a = class_b — дублювання терапії (два препарати одного класу)
CREATE TABLE drug_class_interactions (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_a     int NOT NULL REFERENCES drug_classes (id),
  class_b     int NOT NULL REFERENCES drug_classes (id),
  severity    interaction_severity NOT NULL,
  description text,
  created_at  timestamptz NOT NULL,
  created_by  int REFERENCES users (id),
  updated_at  timestamptz,
  updated_by  int REFERENCES users (id),
  CONSTRAINT ck_drug_class_interactions_order CHECK (class_a <= class_b),
  CONSTRAINT ux_drug_class_interactions UNIQUE (class_a, class_b)
);

