  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medication_a  int NOT NULL REFERENCES medications (id),
  medication_b  int NOT NULL REFERENCES medications (id),
  severity      interaction_severity NOT NULL,
